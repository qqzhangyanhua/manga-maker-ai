"use client";

import { useState } from "react";
import { Button } from "@/components/ui/button";
import {
    Dialog,
    DialogContent,
    DialogDescription,
    DialogFooter,
    DialogHeader,
    DialogTitle,
} from "@/components/ui/dialog";
import { Textarea } from "@/components/ui/textarea";
import { Label } from "@/components/ui/label";
import {
    Select,
    SelectContent,
    SelectItem,
    SelectTrigger,
    SelectValue,
} from "@/components/ui/select";
import { Input } from "@/components/ui/input";
import { Checkbox } from "@/components/ui/checkbox";
import { Loader2, Sparkles } from "lucide-react";
import { useToast } from "@/hooks/use-toast";

interface AutoGenerateDialogProps {
    open: boolean;
    onOpenChange: (open: boolean) => void;
    onWorkflowCreated?: (workflowId: string) => void;
}

export function AutoGenerateDialog({
    open,
    onOpenChange,
    onWorkflowCreated,
}: AutoGenerateDialogProps) {
    const { toast } = useToast();
    const [premise, setPremise] = useState("");
    const [genre, setGenre] = useState("auto");
    const [characterCount, setCharacterCount] = useState("3");
    const [storyLength, setStoryLength] = useState<"short" | "medium" | "long">("medium");
    const [panelCount, setPanelCount] = useState("6");
    const [style, setStyle] = useState("manga");
    const [generateImages, setGenerateImages] = useState(true);
    const [generating, setGenerating] = useState(false);

    async function handleGenerate() {
        if (!premise.trim()) {
            toast({
                title: "错误",
                description: "请输入故事创意",
                variant: "destructive",
            });
            return;
        }

        setGenerating(true);

        try {
            const res = await fetch("/api/workflow/auto-generate", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    premise,
                    genre: genre === "auto" ? undefined : genre,
                    characterCount: parseInt(characterCount) || undefined,
                    storyLength,
                    panelCount: parseInt(panelCount) || undefined,
                    style,
                    generateImages,
                }),
            });

            const data = await res.json();

            if (!res.ok) {
                throw new Error(data.error || "生成失败");
            }

            toast({
                title: "成功",
                description: data.message,
            });

            if (onWorkflowCreated) {
                onWorkflowCreated(data.workflow_id);
            }

            onOpenChange(false);
            resetForm();
        } catch (error) {
            console.error("Auto-generate error:", error);
            const message = error instanceof Error ? error.message : "生成失败";
            toast({
                title: "生成失败",
                description: message,
                variant: "destructive",
            });
        } finally {
            setGenerating(false);
        }
    }

    function resetForm() {
        setPremise("");
        setGenre("auto");
        setCharacterCount("3");
        setStoryLength("medium");
        setPanelCount("6");
        setStyle("manga");
        setGenerateImages(true);
    }

    return (
        <Dialog open={open} onOpenChange={onOpenChange}>
            <DialogContent className="sm:max-w-[600px] max-h-[90vh] overflow-y-auto">
                <DialogHeader>
                    <DialogTitle className="flex items-center gap-2">
                        <Sparkles className="w-5 h-5" />
                        一键生成漫画
                    </DialogTitle>
                    <DialogDescription>
                        输入创意,AI将自动生成完整的漫画(故事→脚本→分镜→图片)
                    </DialogDescription>
                </DialogHeader>

                <div className="space-y-4 py-4">
                    <div className="space-y-2">
                        <Label htmlFor="auto-premise">故事创意 *</Label>
                        <Textarea
                            id="auto-premise"
                            placeholder="例如: 一个失忆的侦探醒来发现自己成了案件的嫌疑人..."
                            value={premise}
                            onChange={(e) => setPremise(e.target.value)}
                            rows={3}
                            className="resize-none"
                        />
                    </div>

                    <div className="grid grid-cols-2 gap-4">
                        <div className="space-y-2">
                            <Label htmlFor="auto-genre">故事类型</Label>
                            <Select value={genre || "auto"} onValueChange={(v) => setGenre(v === "auto" ? "" : v)}>
                                <SelectTrigger id="auto-genre">
                                    <SelectValue placeholder="自动判断" />
                                </SelectTrigger>
                                <SelectContent>
                                    <SelectItem value="auto">自动判断</SelectItem>
                                    <SelectItem value="suspense">悬疑推理</SelectItem>
                                    <SelectItem value="romance">浪漫爱情</SelectItem>
                                    <SelectItem value="adventure">冒险</SelectItem>
                                    <SelectItem value="scifi">科幻</SelectItem>
                                    <SelectItem value="daily">日常</SelectItem>
                                    <SelectItem value="fantasy">奇幻</SelectItem>
                                </SelectContent>
                            </Select>
                        </div>

                        <div className="space-y-2">
                            <Label htmlFor="auto-char-count">主要角色数</Label>
                            <Input
                                id="auto-char-count"
                                type="number"
                                min="1"
                                max="10"
                                value={characterCount}
                                onChange={(e) => setCharacterCount(e.target.value)}
                            />
                        </div>
                    </div>

                    <div className="grid grid-cols-2 gap-4">
                        <div className="space-y-2">
                            <Label htmlFor="auto-length">故事长度</Label>
                            <Select
                                value={storyLength}
                                onValueChange={(value) => {
                                    if (value === "short" || value === "medium" || value === "long") {
                                        setStoryLength(value);
                                    }
                                }}
                            >
                                <SelectTrigger id="auto-length">
                                    <SelectValue />
                                </SelectTrigger>
                                <SelectContent>
                                    <SelectItem value="short">短篇 (3-4分镜)</SelectItem>
                                    <SelectItem value="medium">中篇 (6-8分镜)</SelectItem>
                                    <SelectItem value="long">长篇 (10-12分镜)</SelectItem>
                                </SelectContent>
                            </Select>
                        </div>

                        <div className="space-y-2">
                            <Label htmlFor="auto-panel-count">分镜数量</Label>
                            <Input
                                id="auto-panel-count"
                                type="number"
                                min="3"
                                max="20"
                                value={panelCount}
                                onChange={(e) => setPanelCount(e.target.value)}
                            />
                        </div>
                    </div>

                    <div className="space-y-2">
                        <Label htmlFor="auto-style">画风</Label>
                        <Select value={style} onValueChange={setStyle}>
                            <SelectTrigger id="auto-style">
                                <SelectValue />
                            </SelectTrigger>
                            <SelectContent>
                                <SelectItem value="manga">日式漫画</SelectItem>
                                <SelectItem value="anime">动漫风格</SelectItem>
                                <SelectItem value="realistic">写实风格</SelectItem>
                                <SelectItem value="cartoon">卡通风格</SelectItem>
                            </SelectContent>
                        </Select>
                    </div>

                    <div className="flex items-center space-x-2">
                        <Checkbox
                            id="auto-generate-images"
                            checked={generateImages}
                            onCheckedChange={(checked) => setGenerateImages(checked as boolean)}
                        />
                        <Label
                            htmlFor="auto-generate-images"
                            className="text-sm font-normal cursor-pointer"
                        >
                            自动生成分镜图片 (需要更多时间)
                        </Label>
                    </div>

                    <div className="p-3 bg-muted rounded-md text-sm">
                        <p className="font-medium mb-1">预计耗时:</p>
                        <p className="text-muted-foreground">
                            {generateImages
                                ? `约 ${parseInt(panelCount) * 2 + 3} 分钟`
                                : "约 1-2 分钟"}
                        </p>
                    </div>
                </div>

                <DialogFooter>
                    <Button
                        variant="outline"
                        onClick={() => onOpenChange(false)}
                        disabled={generating}
                    >
                        取消
                    </Button>
                    <Button
                        onClick={handleGenerate}
                        disabled={!premise.trim() || generating}
                    >
                        {generating && <Loader2 className="w-4 h-4 mr-2 animate-spin" />}
                        开始生成
                    </Button>
                </DialogFooter>
            </DialogContent>
        </Dialog>
    );
}
