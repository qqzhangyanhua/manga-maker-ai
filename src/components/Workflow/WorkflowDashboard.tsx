"use client";

import { useState, useEffect } from "react";
import type { WorkflowResult } from "@/lib/type";
import { Button } from "@/components/ui/button";
import {
    Card,
    CardContent,
    CardDescription,
    CardHeader,
    CardTitle,
} from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Progress } from "@/components/ui/progress";
import {
    CheckCircle2,
    Loader2,
    XCircle,
    PlayCircle,
    Clock,
    Sparkles,
} from "lucide-react";
import { AutoGenerateDialog } from "./AutoGenerateDialog";

export interface WorkflowStatusItem {
    id: string;
    status: "pending" | "running" | "completed" | "failed" | "cancelled";
    currentStep: string | null;
    progress: number;
    result?: WorkflowResult | null;
    error?: string;
    createdAt: string;
    startedAt?: string;
    completedAt?: string;
}

interface WorkflowApiPayload {
    id: string;
    status: WorkflowStatusItem["status"];
    currentStep?: string | null;
    current_step?: string | null;
    progress: number;
    result?: WorkflowResult | null;
    error?: string | null;
    createdAt?: string | Date;
    created_at?: string | Date;
    startedAt?: string | Date | null;
    started_at?: string | Date | null;
    completedAt?: string | Date | null;
    completed_at?: string | Date | null;
}

interface WorkflowDashboardProps {
    initialWorkflows?: WorkflowStatusItem[];
}

function toIso(value: string | Date | null | undefined): string {
    if (!value) {
        return new Date().toISOString();
    }

    if (value instanceof Date) {
        return value.toISOString();
    }

    const date = new Date(value);
    return Number.isNaN(date.getTime()) ? new Date().toISOString() : date.toISOString();
}

function normalizeWorkflow(workflow: WorkflowApiPayload): WorkflowStatusItem {
    return {
        id: workflow.id,
        status: workflow.status,
        currentStep: workflow.currentStep ?? workflow.current_step ?? null,
        progress: workflow.progress,
        result: workflow.result ?? null,
        error: workflow.error ?? undefined,
        createdAt: toIso(workflow.createdAt ?? workflow.created_at),
        startedAt: workflow.startedAt || workflow.started_at ? toIso(workflow.startedAt ?? workflow.started_at) : undefined,
        completedAt: workflow.completedAt || workflow.completed_at ? toIso(workflow.completedAt ?? workflow.completed_at) : undefined,
    };
}

const STEP_LABELS: Record<string, string> = {
    story: "生成故事",
    script: "生成脚本",
    storyboard: "生成分镜",
    images: "生成图片",
    export: "导出",
    complete: "完成",
};

const STATUS_CONFIG = {
    pending: { label: "等待中", color: "bg-gray-500", icon: Clock },
    running: { label: "进行中", color: "bg-blue-500", icon: Loader2 },
    completed: { label: "已完成", color: "bg-green-500", icon: CheckCircle2 },
    failed: { label: "失败", color: "bg-red-500", icon: XCircle },
    cancelled: { label: "已取消", color: "bg-gray-500", icon: XCircle },
};

export function WorkflowDashboard({ initialWorkflows = [] }: WorkflowDashboardProps) {
    const [workflows, setWorkflows] = useState<WorkflowStatusItem[]>(initialWorkflows);
    const [loading, setLoading] = useState(false);
    const [showAutoGenerate, setShowAutoGenerate] = useState(false);

    // 仅在没有服务端初始数据时，客户端补拉
    useEffect(() => {
        if (initialWorkflows.length === 0) {
            void loadWorkflows();
        }
    }, [initialWorkflows.length]);

    async function loadWorkflows() {
        setLoading(true);
        try {
            const response = await fetch("/api/workflow?limit=50");
            if (!response.ok) {
                throw new Error("Failed to fetch workflows");
            }
            const data = await response.json();

            if (data.success && data.workflows) {
                const workflowsData = (data.workflows || []) as WorkflowApiPayload[];
                const transformedWorkflows: WorkflowStatusItem[] = workflowsData.map(normalizeWorkflow);
                setWorkflows(transformedWorkflows);
            }
        } catch (error) {
            console.error("Failed to load workflows:", error);
        } finally {
            setLoading(false);
        }
    }

    async function checkWorkflowStatus(workflowId: string) {
        try {
            const res = await fetch(`/api/workflow/${workflowId}/status`);
            const data = await res.json();

            if (data.success) {
                setWorkflows((prev) =>
                    prev.map((workflow) =>
                        workflow.id === workflowId
                            ? normalizeWorkflow(data.workflow as WorkflowApiPayload)
                            : workflow
                    )
                );
            }
        } catch (error) {
            console.error("Failed to check workflow status:", error);
        }
    }

    function handleWorkflowCreated(workflowId: string) {
        // Add new workflow to list and start polling
        const newWorkflow: WorkflowStatusItem = {
            id: workflowId,
            status: "pending",
            currentStep: null,
            progress: 0,
            createdAt: new Date().toISOString(),
        };

        setWorkflows((prev) => [newWorkflow, ...prev]);

        // Poll for status updates
        const interval = setInterval(() => {
            checkWorkflowStatus(workflowId);
        }, 3000);

        // Stop polling after 10 minutes
        setTimeout(() => clearInterval(interval), 600000);
    }

    return (
        <div className="space-y-6 relative">
            <div className="flex items-center justify-between">
                <Button
                    onClick={() => setShowAutoGenerate(true)}
                    className="bg-orange-500 hover:bg-orange-600 text-white border-0 shadow-lg shadow-orange-500/20"
                >
                    <Sparkles className="w-4 h-4 mr-2" />
                    一键生成漫画
                </Button>
            </div>

            {workflows.length === 0 ? (
                <Card className="relative border-zinc-700 bg-zinc-900/60 backdrop-blur-md overflow-hidden shadow-lg">
                    <div className="absolute top-0 left-0 right-0 h-px bg-gradient-to-r from-transparent via-zinc-600 to-transparent" />
                    <CardContent className="py-12 relative z-10">
                        <div className="text-center space-y-4">
                            <PlayCircle className="w-16 h-16 mx-auto text-orange-500" />
                            <div>
                                <h3 className="text-lg font-semibold text-white">还没有工作流</h3>
                                <p className="text-sm text-zinc-400 mt-2">
                                    点击"一键生成漫画"开始创作
                                </p>
                            </div>
                        </div>
                    </CardContent>
                </Card>
            ) : (
                <div className="grid grid-cols-1 gap-4">
                    {workflows.map((workflow) => (
                        <WorkflowCard
                            key={workflow.id}
                            workflow={workflow}
                            onRefresh={() => checkWorkflowStatus(workflow.id)}
                        />
                    ))}
                </div>
            )}

            <AutoGenerateDialog
                open={showAutoGenerate}
                onOpenChange={setShowAutoGenerate}
                onWorkflowCreated={handleWorkflowCreated}
            />
        </div>
    );
}

function WorkflowCard({
    workflow,
    onRefresh,
}: {
    workflow: WorkflowStatusItem;
    onRefresh: () => void;
}) {
    const statusConfig = STATUS_CONFIG[workflow.status];
    const StatusIcon = statusConfig.icon;

    return (
        <Card className="relative border-zinc-700 bg-zinc-900/60 backdrop-blur-md overflow-hidden shadow-lg hover:shadow-xl hover:shadow-orange-500/10 hover:-translate-y-1 transition-all">
            <div className="absolute top-0 left-0 right-0 h-px bg-gradient-to-r from-transparent via-zinc-600 to-transparent" />
            <CardHeader className="relative z-10">
                <div className="flex items-start justify-between">
                    <div className="flex-1">
                        <CardTitle className="text-base flex items-center gap-2 text-white">
                            工作流 #{workflow.id.slice(0, 8)}
                            <Badge className={statusConfig.color}>
                                {statusConfig.label}
                            </Badge>
                        </CardTitle>
                        <CardDescription className="mt-1 text-zinc-400">
                            创建时间: {new Date(workflow.createdAt).toLocaleString()}
                        </CardDescription>
                    </div>
                    <StatusIcon
                        className={`w-5 h-5 text-zinc-400 ${workflow.status === "running" ? "animate-spin" : ""
                            }`}
                    />
                </div>
            </CardHeader>
            <CardContent className="space-y-4 relative z-10">
                {workflow.status === "running" && (
                    <div className="space-y-2">
                        <div className="flex items-center justify-between text-sm">
                            <span className="text-zinc-300">
                                当前步骤:{" "}
                                {workflow.currentStep
                                    ? STEP_LABELS[workflow.currentStep]
                                    : "准备中"}
                            </span>
                            <span className="text-zinc-300">{workflow.progress}%</span>
                        </div>
                        <Progress value={workflow.progress} />
                    </div>
                )}

                {workflow.status === "completed" && workflow.result && (
                    <div className="grid grid-cols-2 gap-2 text-sm">
                        {workflow.result.storyId && (
                            <div>
                                <span className="text-zinc-400">故事ID:</span>{" "}
                                <span className="text-white">{workflow.result.storyId.slice(0, 8)}</span>
                            </div>
                        )}
                        {workflow.result.projectId && (
                            <div>
                                <span className="text-zinc-400">项目ID:</span>{" "}
                                <span className="text-white">{workflow.result.projectId.slice(0, 8)}</span>
                            </div>
                        )}
                        {workflow.result.panelCount && (
                            <div>
                                <span className="text-zinc-400">分镜数:</span>{" "}
                                <span className="text-white">{workflow.result.panelCount}</span>
                            </div>
                        )}
                        {workflow.result.generatedImages !== undefined && (
                            <div>
                                <span className="text-zinc-400">生成图片:</span>{" "}
                                <span className="text-white">{workflow.result.generatedImages}</span>
                            </div>
                        )}
                    </div>
                )}

                {workflow.status === "failed" && workflow.error && (
                    <div className="p-3 bg-red-950/30 border border-red-500/30 text-red-400 rounded-md text-sm">
                        {workflow.error}
                    </div>
                )}

                <div className="flex gap-2">
                    {workflow.status === "running" && (
                        <Button
                            variant="outline"
                            size="sm"
                            onClick={onRefresh}
                            className="border-zinc-700 bg-zinc-800/50 text-zinc-300 hover:bg-zinc-800 hover:text-white hover:border-orange-500/50"
                        >
                            刷新状态
                        </Button>
                    )}
                    {workflow.status === "completed" && workflow.result?.projectId && (
                        <Button
                            size="sm"
                            onClick={() => {
                                window.location.href = `/storyboard?project_id=${workflow.result.projectId}`;
                            }}
                            className="bg-orange-500 hover:bg-orange-600 text-white border-0 shadow-lg shadow-orange-500/20"
                        >
                            查看项目
                        </Button>
                    )}
                    {workflow.status === "failed" && (
                        <Button
                            variant="outline"
                            size="sm"
                            onClick={async () => {
                                try {
                                    await fetch(`/api/workflow/${workflow.id}/resume`, {
                                        method: "POST",
                                    });
                                    onRefresh();
                                } catch (error) {
                                    console.error("Resume failed:", error);
                                }
                            }}
                            className="border-zinc-700 bg-zinc-800/50 text-zinc-300 hover:bg-zinc-800 hover:text-white hover:border-orange-500/50"
                        >
                            重试
                        </Button>
                    )}
                </div>
            </CardContent>
        </Card>
    );
}
